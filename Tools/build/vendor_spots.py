"""Build the compact vendor-material seller index used by Professions.

Classic vendor inventories come from Wowhead's item pages. Coordinates and faction are not
copied: the generated index names sellers already present in Shared/Game/Towns.lua, whose
positions include Forever's corrected maps. Merchant visits extend that built-in index at
runtime when Forever adds or moves a seller.

Usage: python Tools/build/vendor_spots.py [--offline]
"""
import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
from sources.wowhead import fetch, listview, lua_string  # noqa: E402

ROOT = paths.ROOT
REAGENTS = ROOT / "NaowhForever_Professions" / "Data" / "VendorReagents.lua"
TOWNS = ROOT / "Shared" / "Game" / "Towns.lua"
OUT = ROOT / "NaowhForever_Professions" / "Data" / "VendorSellers.lua"
CACHE = paths.DATA / "vendor_sellers.json"
WOWHEAD = "https://www.wowhead.com/classic"


def reagent_ids(text=None):
    text = REAGENTS.read_text(encoding="utf-8") if text is None else text
    return sorted({int(item) for item in re.findall(r"\[(\d+)\]\s*=\s*true", text)})


def town_names(text=None):
    text = TOWNS.read_text(encoding="utf-8") if text is None else text
    rows = re.findall(r'^\s*\{\s*[\d.]+,\s*[\d.]+,\s*"[^"]+",\s*"((?:[^"\\]|\\.)*)",\s*"([^"]*)"', text, re.M)
    return {name for name, title in rows if not title.startswith("Darkmoon Faire")}


def seller_rows(item_id):
    page = fetch(f"{WOWHEAD}/item={item_id}")
    return sorted({
        row["name"]
        for row in listview(page, "sold-by")
        if row.get("stock") == -1 and row.get("name")
    })


def load_rows(offline):
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    for item_id in reagent_ids():
        key = str(item_id)
        if key not in cache:
            if offline:
                raise SystemExit(f"vendor seller cache has no item {item_id}")
            cache[key] = seller_rows(item_id)
    normalized = {
        key: sorted({row["name"] if isinstance(row, dict) else row for row in sellers})
        for key, sellers in cache.items()
    }
    if normalized != cache:
        cache = normalized
    CACHE.write_text(json.dumps(cache, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return cache


def mapped_sellers(rows, reagents=None, towns=None):
    reagents = reagent_ids() if reagents is None else reagents
    towns = town_names() if towns is None else towns
    return {
        item_id: sorted({name for name in rows[str(item_id)] if name in towns})
        for item_id in reagents
    }


def render(rows, reagents=None, towns=None):
    by_item = mapped_sellers(rows, reagents, towns)

    names = sorted({name for sellers in by_item.values() for name in sellers})
    indexes = {name: i for i, name in enumerate(names, 1)}
    lines = [
        "-- VendorSellers.lua: unlimited profession reagent sellers, generated by Tools/build/vendor_spots.py.",
        "local P = _G.NaowhForever.Professions",
        "",
        "P.VendorSellerNames = {",
    ]
    for name in names:
        lines.append(f"    {lua_string(name)},")
    lines.extend(["}", "", "P.VendorSellers = {"])
    for item_id, sellers in by_item.items():
        refs = ", ".join(str(indexes[name]) for name in sellers)
        lines.append(f"    [{item_id}] = {{ {refs} }},")
    lines.extend(["}", ""])
    return "\r\n".join(lines), by_item, names


def write(rows):
    text, by_item, names = render(rows)
    OUT.write_text(text, encoding="utf-8", newline="")
    covered = sum(bool(sellers) for sellers in by_item.values())
    print(f"{len(names)} sellers cover {covered}/{len(by_item)} vendor reagents -> {OUT.name}", file=sys.stderr)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()
    write(load_rows(args.offline))


if __name__ == "__main__":
    main()
