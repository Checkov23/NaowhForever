-- Run from the repo root: lua5.1 Tools/build/transport.lua [output path].
-- Freeze Journeys' dwell and leg estimates for QoL without a runtime dependency on Journeys.
local ns = { Journeys = {} }
local function Load(path)
    local chunk = assert(loadfile(path))
    setfenv(chunk, { _G = { NaowhForever = ns } })
    chunk()
end
Load("NaowhForever_Journeys/Constants.lua")
Load("NaowhForever_Journeys/Data/Network.lua")
Load("NaowhForever_QoL/Interface/TownTravel.lua")

local timings = {}
for s, ship in ipairs(ns.JourneyNetwork.ships) do
    local period = 0
    for i = 3, #ship do
        period = period + ship[i][6] + ship[i][7] / ns.Journeys.C.SHIP_SPEED[ship[1]]
    end
    for i = 3, #ship do
        for j = 3, #ship do
            if i ~= j then
                local key = ship[i][4] .. ":" .. ship[1] .. " to " .. ship[j][5]
                assert(not timings[key], "ambiguous dock: " .. key)
                timings[key] = { period = period, dwell = ship[i][6], stop = s .. ":" .. i }
            end
        end
    end
end

local maps = {}
for map in pairs(ns.TownTravel) do maps[#maps + 1] = map end
table.sort(maps)
local lines = {
    "-- TransportData.lua: estimated dock periods and dwells, generated by Tools/build/transport.lua.",
    "local ns = _G.NaowhForever",
    "",
    "ns.TransportData = {",
}
-- One ship's stop at one dock shares a sighting key, whichever destination is chosen there.
local sightings = {}
for _, map in ipairs(maps) do
    for index, pin in ipairs(ns.TownTravel[map]) do
        for label = 4, #pin, 2 do
            local timing = assert(timings[map .. ":" .. pin[label]], "dock missing from Journeys")
            local key = map .. ":" .. index .. ":" .. label
            sightings[timing.stop] = sightings[timing.stop] or key
            lines[#lines + 1] = ('    ["%s"] = { period = %.6f, dwell = %d, sighting = "%s" },'):format(
                key, timing.period, timing.dwell, sightings[timing.stop])
        end
    end
end
lines[#lines + 1] = "}"
local path = arg[1] or "NaowhForever_QoL/Travel/TransportData.lua"
local output = assert(io.open(path, "wb"))
output:write(table.concat(lines, "\r\n"), "\r\n")
output:close()
print("Transport timings -> " .. path)
