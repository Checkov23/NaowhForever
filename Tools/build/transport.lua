-- Run from the repo root: lua5.1 Tools/build/transport.lua [output path].
-- Freeze each boat and zeppelin stop from Journeys' network for QoL, without a runtime dependency on Journeys.
local ns = { Journeys = {} }
local function Load(path)
    local chunk = assert(loadfile(path))
    setfenv(chunk, { _G = { NaowhForever = ns } })
    chunk()
end
Load("NaowhForever_Utilities/Journeys/Constants.lua")
Load("NaowhForever_Utilities/Journeys/Data/Network.lua")

-- Published cycle times in seconds, by the docks a ship joins in sorted order: warcraft.wiki.gg,
-- "Travel guide to zeppelins and boats" (Undercity-Orgrimmar every 3:59, Undercity-Grom'gol every 5:15).
-- A ship without one keeps Journeys' estimate: every dock's wait plus every leg's yards over its speed.
local PUBLISHED = { ["Orgrimmar/Undercity"] = 239, ["Grom'gol/Undercity"] = 315 }

local stops, keys, used = {}, {}, {}
for _, ship in ipairs(ns.JourneyNetwork.ships) do
    local period, places = 0, {}
    for i = 3, #ship do
        period = period + ship[i][6] + ship[i][7] / ns.Journeys.C.SHIP_SPEED[ship[1]]
        places[#places + 1] = ship[i][5]
    end
    table.sort(places)
    local route = table.concat(places, "/")
    if PUBLISHED[route] then
        assert(not used[route], "two ships join " .. route)
        period, used[route] = PUBLISHED[route], true
    end
    for i = 3, #ship do
        local stop = ship[i]
        local routes = {}
        for step = 1, #ship - 3 do
            local to = ship[3 + (i - 3 + step) % (#ship - 2)]
            routes[#routes + 1] = ('"%s to %s"'):format(ship[1], to[5])
        end
        local key = stop[4] .. ":" .. ship[1] .. " to " .. ship[3 + (i - 2) % (#ship - 2)][5]
        assert(not stops[key], "two stops share " .. key)
        stops[key] = ('{ map = %d, continent = %d, x = %.1f, y = %.1f, side = "%s", period = %.6f, dwell = %d,'
            .. ' routes = { %s } }'):format(stop[4], stop[1], stop[2], stop[3], ship[2], period, stop[6],
            table.concat(routes, ", "))
        keys[#keys + 1] = key
    end
end
for route in pairs(PUBLISHED) do assert(used[route], "no ship joins " .. route) end
table.sort(keys)

local lines = {
    "-- TransportData.lua: each boat and zeppelin stop, its period and dwell, generated by Tools/build/transport.lua.",
    "local ns = _G.NaowhForever",
    "",
    "ns.TransportData = {",
}
for _, key in ipairs(keys) do
    lines[#lines + 1] = ('    ["%s"] = %s,'):format(key, stops[key])
end
lines[#lines + 1] = "}"
local path = arg[1] or "NaowhForever_QoL/Travel/TransportData.lua"
local output = assert(io.open(path, "wb"))
output:write(table.concat(lines, "\r\n"), "\r\n")
output:close()
print("Transport timings -> " .. path)
