"""Build the zone maps the game has twice, from its own tables (Tools/sources/wago.py).

Forever has zone maps that are one place under two uiMapIDs: the same name, continent and
bounds (UiMapAssignment), so a map percentage is the same spot on both. Zephras Isle is 2521,
under Azeroth, and 2665, with no parent; the game puts players on either. The addon's data is
keyed by the one with a parent, so each other one is written as an alias of it, and the addon
reads that map's data for it.

Writes Shared/Data/SameMaps.lua.

Usage: python Tools/build/same_maps.py [--build 1.60.1.70374]
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402,F401
import wago  # noqa: E402
from journal import ROOT, header, write  # noqa: E402

OUT = ROOT / "Shared" / "Data" / "SameMaps.lua"
SLACK = 1   # yards: the game stores one map's bounds a few thousandths off the other's


def same_maps(ui_maps, assignments):
    """{ alias uiMapID: the uiMapID whose data it reads } for each zone map that shares its
    name, type, continent and bounds with another."""
    names = {row["ID"]: (row["Name_lang"], row["Type"]) for row in ui_maps}
    placed = []
    for row in assignments:
        if row["OrderIndex"] == "0" and row["UiMapID"] in names:
            bounds = tuple(float(row[f"Region_{i}"]) for i in (0, 1, 3, 4))
            placed.append((int(row["UiMapID"]), names[row["UiMapID"]], row["MapID"], bounds))
    parents = {int(row["ID"]): int(row["ParentUiMapID"]) for row in ui_maps}
    groups = []
    for map_id, name, continent, bounds in sorted(placed):
        for group in groups:
            _, other_name, other_continent, other_bounds = group[0]
            if (name, continent) == (other_name, other_continent) and all(
                    abs(a - b) <= SLACK for a, b in zip(bounds, other_bounds)):
                group.append((map_id, name, continent, bounds))
                break
        else:
            groups.append([(map_id, name, continent, bounds)])
    aliases = {}
    for group in groups:
        if len(group) < 2:
            continue
        ids = [entry[0] for entry in group]
        kept = [map_id for map_id in ids if parents[map_id]]
        if len(kept) != 1:
            sys.exit(f"maps {ids} are one place, but {len(kept)} of them have a parent map, not 1")
        for map_id in ids:
            if map_id != kept[0]:
                aliases[map_id] = kept[0]
    return aliases


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--build", default=wago.BUILD)
    build = parser.parse_args().build

    aliases = same_maps(wago.table("UiMap", build), wago.table("UiMapAssignment", build))
    # [uiMapID] = the uiMapID whose data it reads.
    lines = header(OUT.name, "maps the game has under two IDs, generated by Tools/build/same_maps.py")
    lines.append("ns.Shared.SameMaps = {")
    for map_id in sorted(aliases):
        lines.append(f"    [{map_id}] = {aliases[map_id]},")
    lines.append("}")
    write(OUT, lines)
    print(f"{len(aliases)} maps -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
