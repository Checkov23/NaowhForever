-- Writes NaowhForever_SearchIndex/SearchIndex.lua (ns.SEARCH_INDEX): every module page's search entries, so the
-- options window can still search a module that is turned off, whose addon the game never loads.
-- Runs every file the TOCs load against a stub world that answers any API call with another stub,
-- then reads each module page through Settings.Index as the window would. Rebuild from the repo root
-- with Libs/ after changing a module's settings; test-search-index-current.lua fails until then:
--   lua5.1 Tools/build/search_index.lua
local OUT = "NaowhForever_SearchIndex/SearchIndex.lua"
local TocFiles = dofile("Tools/regression/toc_files.lua")

local Stub
local stubMeta = {}
stubMeta.__index = function(t, k)
    local v = Stub()
    rawset(t, k, v)
    return v
end
stubMeta.__call = function() return Stub() end
stubMeta.__tostring = function() return "" end
stubMeta.__concat = function(a, b)
    return (type(a) == "string" and a or "") .. (type(b) == "string" and b or "")
end
for _, op in ipairs({ "__add", "__sub", "__mul", "__div", "__mod", "__pow", "__unm" }) do
    stubMeta[op] = function() return 0 end
end
stubMeta.__lt = function() return false end
stubMeta.__le = function() return false end
function Stub() return setmetatable({}, stubMeta) end

-- The addon's own globals and saved variables start unset, as on a first login.
local env = setmetatable({}, { __index = function(t, k)
    local v = _G[k]
    if v ~= nil then return v end
    if k:find("^NaowhForever") then return nil end
    v = Stub()
    rawset(t, k, v)
    return v
end })
env._G = env
env.GetLocale = function() return "enUS" end
env.C_AddOns = { IsAddOnLoaded = function() return true end, DoesAddOnExist = function(name) return io.open(name .. "/" .. name .. ".toc") ~= nil end, GetAddOnMetadata = function() return "" end,
    GetAddOnEnableState = function() return 2 end, LoadAddOn = function() return true end }
env.MAX_PARTY_MEMBERS, env.MAX_RAID_MEMBERS = 4, 40
env.MerchantFrame = { IsShown = function() return false end }
env.ClassTrainerFrame = { IsShown = function() return false end }
env.C_ClassColor = { GetClassColor = function()
    return { WrapTextInColorCode = function(_, text) return text end }
end }
env.LOCALIZED_CLASS_NAMES_MALE = setmetatable({}, { __index = function(_, class)
    return class:sub(1, 1) .. class:sub(2):lower()
end })

for _, path in ipairs(TocFiles("%.lua$")) do
    local skip = path:find("^Libs/") or path:find("SearchIndex%.lua$") or (path:find("Locales/") and path ~= "Core/Locales/enUS.lua")
    if not skip then
        local chunk = assert(loadfile(path))
        setfenv(chunk, env)
        chunk(path:match("^(NaowhForever_[^/]+)/") or "NaowhForever", rawget(env, "NaowhForever"))
    end
end

local ns = rawget(env, "NaowhForever")
local Settings = ns.Shared.Settings

-- Addon files are ASCII, so every byte past it is written as a decimal escape.
local function Quote(s)
    if type(s) ~= "string" then return "false" end
    s = s:gsub('[\\"]', "\\%0"):gsub("\r", "\\r"):gsub("\n", "\\n")
    return '"' .. s:gsub("[\128-\255]", function(c) return "\\" .. c:byte() end) .. '"'
end

local out = {
    "-- SearchIndex.lua: every module page's search entries (ns.SEARCH_INDEX), generated by Tools/build/search_index.lua.",
    "local ns = _G.NaowhForever",
    "",
    "ns.SEARCH_INDEX = {",
}
for _, mod in ipairs(ns.Options.MODULES) do
    for _, tab in ipairs(mod.tabs) do
        local lines = {}
        Settings.Index(tab.key, function(uid, label, help, cardName, group)
            if type(label) ~= "string" then return end
            local id = uid:match("^.*:([^:]+)$")
            if cardName == nil then label, cardName = nil, label end
            lines[#lines + 1] = ("        { %s, %s, %s, %s, %s },"):format(Quote(id), Quote(label), Quote(help),
                Quote(cardName), Quote(group))
        end)
        if #lines > 0 then
            out[#out + 1] = ("    [%s] = {"):format(Quote(tab.key))
            for _, line in ipairs(lines) do out[#out + 1] = line end
            out[#out + 1] = "    },"
        end
    end
end
out[#out + 1] = "}"
local text = table.concat(out, "\r\n") .. "\r\n"

if arg and arg[0] and arg[0]:find("search_index%.lua$") then
    local f = assert(io.open(OUT, "wb"))
    f:write(text)
    f:close()
    print(("%s: %d lines"):format(OUT, #out))
end
return text
