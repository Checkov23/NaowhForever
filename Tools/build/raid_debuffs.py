"""Build Raid Debuffs' spell list from the game's own spell tables (Tools/sources/wago.py).

Each entry is one slot on the bar: every rank, and the NPC and item versions, of the debuffs a
raid keeps on a boss. The AuraContainer picks an enemy's debuffs by spell ID only, so names are
matched here and the addon reads IDs. Every entry must find at least one spell, or the build
stops: a renamed spell is caught here, not in game.

Writes NaowhForever_Combat/RaidDebuffs/Data/Spells.lua.

Usage: python Tools/build/raid_debuffs.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import paths  # noqa: E402
import wago  # noqa: E402
from pvp_auras import auras_by_spell, lua_entries, resolve  # noqa: E402

ROOT = paths.ROOT
OUT = ROOT / "NaowhForever_Combat" / "RaidDebuffs" / "Data" / "Spells.lua"

# (key, group, label, names or spell IDs)
DEBUFFS = [
    ("sunderArmor", "Warrior", "Sunder Armor", ["Sunder Armor"]),
    ("demoralizingShout", "Warrior", "Demoralizing Shout", ["Demoralizing Shout"]),
    ("thunderClap", "Warrior", "Thunder Clap", ["Thunder Clap"]),
    ("exposeArmor", "Rogue", "Expose Armor", ["Expose Armor"]),
    ("faerieFire", "Druid", "Faerie Fire", ["Faerie Fire", "Faerie Fire (Feral)"]),
    ("demoralizingRoar", "Druid", "Demoralizing Roar", ["Demoralizing Roar"]),
    ("curseOfRecklessness", "Warlock", "Curse of Recklessness", ["Curse of Recklessness"]),
    ("curseOfElements", "Warlock", "Curse of the Elements", ["Curse of the Elements"]),
    ("curseOfShadow", "Warlock", "Curse of Shadow", ["Curse of Shadow"]),
    ("shadowVulnerability", "Warlock", "Shadow Vulnerability", ["Shadow Vulnerability"]),
    ("huntersMark", "Hunter", "Hunter's Mark", ["Hunter's Mark"]),
    ("judgementOfWisdom", "Paladin", "Judgement of Wisdom", ["Judgement of Wisdom"]),
    ("judgementOfLight", "Paladin", "Judgement of Light", ["Judgement of Light"]),
    ("judgementOfTheCrusader", "Paladin", "Judgement of the Crusader", ["Judgement of the Crusader"]),
    ("shadowWeaving", "Priest", "Shadow Weaving", ["Shadow Weaving"]),
    ("wintersChill", "Mage", "Winter's Chill", ["Winter's Chill"]),
    ("fireVulnerability", "Mage", "Fire Vulnerability", ["Fire Vulnerability"]),
]


def write(debuffs, icons, build):
    lines = [
        f"-- {OUT.name}: Raid Debuffs' spells by ID, generated by Tools/build/raid_debuffs.py from build {build}.",
        "local ns = _G.NaowhForever",
        "",
        "ns.RaidDebuffSpells = {",
    ]
    lines += [line[4:] for line in lua_entries(debuffs, icons)]
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(("\r\n".join(lines) + "\r\n").encode("ascii"))
    spells = sum(len(ids) for _, _, _, ids in debuffs)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(debuffs)} debuffs ({spells} spells)")


def main():
    names = {int(r["ID"]): r["Name_lang"] for r in wago.table("SpellName")}
    auras = auras_by_spell(wago.table("SpellEffect"))
    icons = {int(r["SpellID"]): int(r["SpellIconFileDataID"] or 0) for r in wago.table("SpellMisc")}
    debuffs = resolve(DEBUFFS, names, auras, lambda a: bool(a - {0}))
    write(debuffs, icons, wago.BUILD)


if __name__ == "__main__":
    main()
