"""Build the built-in prices of the Professions vendor reagents.

A reagent's merchant price is in the Forever client's own item table: ItemSparse's BuyPrice,
in copper, for VendorStackCount items. It is read through the project's wago reader for
wago.BUILD, with its hotfixes. An item with no ItemSparse row (the server sends its data) gets
no built-in price and is learned at a merchant as before. Cached in data/vendor_prices.json;
--offline rebuilds from the cache.

Usage: python Tools/build/vendor_prices.py [--offline]
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402
import wago  # noqa: E402
from vendor_spots import reagent_ids  # noqa: E402

OUT = paths.ROOT / "NaowhForever_Professions" / "Data" / "VendorPrices.lua"
CACHE = paths.DATA / "vendor_prices.json"


def read_rows(ids, rows):
    """Item ID (as text) -> [BuyPrice, VendorStackCount] for each wanted item sold for copper."""
    wanted, found = set(ids), {}
    for row in rows:
        item, buy = int(row["ID"]), int(row["BuyPrice"] or 0)
        if item in wanted and buy > 0:
            found[str(item)] = [buy, max(int(row["VendorStackCount"] or 1), 1)]
    return found


def load_rows(offline):
    if offline:
        return json.loads(CACHE.read_text(encoding="utf-8"))
    rows = read_rows(reagent_ids(), wago.table("ItemSparse"))
    CACHE.write_text(json.dumps(rows, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return rows


def each_price(buy, stack):
    price = buy / stack
    return int(price) if price == int(price) else round(price, 2)


def render(rows, reagents=None):
    reagents = reagent_ids() if reagents is None else reagents
    priced = [item for item in reagents if str(item) in rows]
    lines = [
        "-- VendorPrices.lua: each vendor reagent's merchant price in copper, generated by Tools/build/vendor_prices.py.",
        "local P = _G.NaowhForever.Professions",
        "",
        "P.VendorPrices = {",
    ]
    for item in priced:
        lines.append(f"    [{item}] = {each_price(*rows[str(item)])},")
    lines.extend(["}", ""])
    return "\r\n".join(lines), priced


def write(rows):
    text, priced = render(rows)
    OUT.write_text(text, encoding="utf-8", newline="")
    print(f"{len(priced)}/{len(reagent_ids())} vendor reagents priced -> {OUT.name}", file=sys.stderr)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()
    write(load_rows(args.offline))


if __name__ == "__main__":
    main()
