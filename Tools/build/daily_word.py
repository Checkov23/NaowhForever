"""Build the Daily Word's words: the answers, one a day in a fixed order, and every word it accepts.

Both lists are public domain. The answers are the five-letter words of 12dicts' 2of12 (words in
at least two of twelve dictionaries) that are also in 3esl (its list for learners of English),
leaving out plurals and past tenses of other words in it and the words in LEFT_OUT. Every
answer and every five-letter word of ENABLE is accepted as a guess.

The answers are shuffled with a fixed seed, so a run gives the same order every time; the addon
picks day N's answer by its place in that order. Changing the sources, LEFT_OUT or SEED changes
the words of days already played.

Writes NaowhForever_QoL/Travel/DailyWordData.lua.

Usage: python Tools/build/daily_word.py
"""
import io
import random
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import paths  # noqa: E402,F401
from journal import ROOT, header, write  # noqa: E402

OUT = ROOT / "NaowhForever_QoL" / "Travel" / "DailyWordData.lua"
ENABLE = "https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt"
TWELVE_DICTS = "http://downloads.sourceforge.net/wordlist/12dicts-6.0.2.zip"
COMMON, LEARNER = "American/2of12.txt", "American/3esl.txt"
SEED = 20741
WORD = re.compile(r"[a-z]{5}")
LEFT_OUT = set("""
    abort bigot bimbo bitch booty bosom bowel chink erect fanny feces gypsy harem horny idiot kinky
    lynch moron naked pansy prick pubic pussy queer semen slave spade sperm tramp urine vomit whore
""".split())


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def inflected(word, base):
    """True for a plural or past tense of another word in base."""
    if word.endswith("s") and (word[:-1] in base or word[:-2] in base):
        return True
    if word.endswith("ies") and word[:-3] + "y" in base:
        return True
    return word.endswith("ed") and (word[:-2] in base or word[:-1] in base)


def words(enable_text, twelve_zip):
    enable = {w for w in enable_text.split() if WORD.fullmatch(w)}
    with zipfile.ZipFile(io.BytesIO(twelve_zip)) as z:
        common = set(z.read(COMMON).decode("latin-1").split())
        learner = set(z.read(LEARNER).decode("latin-1").split())
    answers = sorted(w for w in common & learner
                     if WORD.fullmatch(w) and w in enable and w not in LEFT_OUT and not inflected(w, common))
    random.Random(SEED).shuffle(answers)
    return answers, sorted(enable | set(answers))


def main():
    answers, accepted = words(fetch(ENABLE).decode("ascii"), fetch(TWELVE_DICTS))
    lines = header("DailyWordData.lua", "the Daily Word's answers in play order and every word it accepts, "
                   "sorted, five letters each, from 12dicts and ENABLE (public domain), generated by "
                   "Tools/build/daily_word.py")
    lines += [f'ns.DailyWordAnswers = "{"".join(answers)}"', f'ns.DailyWordWords = "{"".join(accepted)}"']
    write(OUT, lines)
    print(f"{len(answers)} answers, {len(accepted)} accepted words")


if __name__ == "__main__":
    main()
